
-- SOAL 3: DATABASE VOUCHER KAS KELUAR
-- PostgreSQL / Supabase

-- 1. MASTER AKUN
CREATE TABLE IF NOT EXISTS public.chart_of_accounts (
    account_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_code VARCHAR(20) NOT NULL UNIQUE,
    account_name VARCHAR(150) NOT NULL,
    normal_balance CHAR(1) NOT NULL
        CHECK (normal_balance IN ('D', 'K')),
    report_classification VARCHAR(30) NOT NULL
        CHECK (
            report_classification IN (
                'ASET', 'LIABILITAS', 'EKUITAS',
                'PENDAPATAN', 'BEBAN'
            )
        ),
    is_cash_or_equivalent BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. HEADER JURNAL
CREATE TABLE IF NOT EXISTS public.journal_headers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trx_date DATE NOT NULL,
    ref_number VARCHAR(50) NOT NULL UNIQUE,
    description TEXT NOT NULL,
    status_posting VARCHAR(10) NOT NULL DEFAULT 'DRAFT'
        CHECK (status_posting IN ('DRAFT', 'POSTED')),
    created_by UUID DEFAULT auth.uid()
        REFERENCES auth.users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    posted_at TIMESTAMPTZ,
    hash_checksum VARCHAR(64)
);

-- 3. RINCIAN JURNAL
CREATE TABLE IF NOT EXISTS public.journal_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    header_id BIGINT NOT NULL
        REFERENCES public.journal_headers(id) ON DELETE RESTRICT,
    account_id BIGINT NOT NULL
        REFERENCES public.chart_of_accounts(account_id) ON DELETE RESTRICT,
    debit NUMERIC(18,2) NOT NULL DEFAULT 0
        CHECK (debit >= 0),
    credit NUMERIC(18,2) NOT NULL DEFAULT 0
        CHECK (credit >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    -- Setiap baris harus berisi debit atau kredit, bukan keduanya
    CONSTRAINT chk_journal_line_one_side
        CHECK (
            (debit > 0 AND credit = 0)
            OR
            (credit > 0 AND debit = 0)
        )
);

-- 4. LOG AUDIT
CREATE TABLE IF NOT EXISTS public.audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_name TEXT NOT NULL,
    record_id TEXT NOT NULL,
    operation VARCHAR(10) NOT NULL
        CHECK (operation IN ('INSERT', 'UPDATE', 'DELETE')),
    actor_id UUID DEFAULT auth.uid()
        REFERENCES auth.users(id) ON DELETE SET NULL,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    old_data JSONB,
    new_data JSONB
);

-- 5. INDEX UNTUK PENCARIAN
CREATE INDEX IF NOT EXISTS idx_journal_lines_header
    ON public.journal_lines(header_id);

CREATE INDEX IF NOT EXISTS idx_journal_lines_account
    ON public.journal_lines(account_id);

CREATE INDEX IF NOT EXISTS idx_audit_log_occurred_at
    ON public.audit_log(occurred_at);

