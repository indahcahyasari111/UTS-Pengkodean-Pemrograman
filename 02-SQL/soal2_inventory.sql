
-- UTS PEMROGRAMAN
-- SOAL 2: OTOMATISASI PERSEDIAAN
-- Database: PostgreSQL

-- =====================================================
-- 1. MEMBUAT TABEL MASTER PERSEDIAAN
-- =====================================================

CREATE TABLE IF NOT EXISTS inventory_items (
    item_id VARCHAR(10) PRIMARY KEY,
    item_name VARCHAR(100) NOT NULL,
    stock_qty INT NOT NULL DEFAULT 0
        CHECK (stock_qty >= 0),
    unit_cost NUMERIC(15,2) NOT NULL
        CHECK (unit_cost >= 0)
);

-- =====================================================
-- 2. MEMBUAT TABEL TRANSAKSI PERSEDIAAN
-- =====================================================

CREATE TABLE IF NOT EXISTS inventory_transactions (
    trx_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id VARCHAR(10) NOT NULL
        REFERENCES inventory_items(item_id)
        ON DELETE RESTRICT,
    trx_type VARCHAR(10) NOT NULL
        CHECK (trx_type IN ('PURCHASE', 'SALE', 'ADJUSTMENT')),
    qty INT NOT NULL,
    trx_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- =====================================================
-- 3. MEMBUAT TRIGGER FUNCTION
-- =====================================================

CREATE OR REPLACE FUNCTION trg_update_stock_and_journal()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_current_stock INT;
    v_delta INT;
BEGIN
    -- Kuantitas transaksi tidak boleh nol
    IF NEW.qty = 0 THEN
        RAISE EXCEPTION 'Kuantitas transaksi tidak boleh nol';
    END IF;

    -- Pembelian dan penjualan harus menggunakan kuantitas positif
    IF NEW.trx_type IN ('PURCHASE', 'SALE')
       AND NEW.qty < 0 THEN
        RAISE EXCEPTION
            'Kuantitas PURCHASE dan SALE harus positif';
    END IF;

    -- Mengunci baris item untuk mencegah race condition
    SELECT stock_qty
    INTO v_current_stock
    FROM inventory_items
    WHERE item_id = NEW.item_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Item % tidak ditemukan', NEW.item_id;
    END IF;

    -- Menentukan perubahan jumlah stok
    CASE NEW.trx_type
        WHEN 'PURCHASE' THEN
            v_delta := NEW.qty;

        WHEN 'SALE' THEN
            v_delta := -NEW.qty;

        WHEN 'ADJUSTMENT' THEN
            v_delta := NEW.qty;

        ELSE
            RAISE EXCEPTION
                'Jenis transaksi tidak valid: %', NEW.trx_type;
    END CASE;

    -- Mencegah saldo stok menjadi negatif
    IF v_current_stock + v_delta < 0 THEN
        RAISE EXCEPTION
            'Stok tidak mencukupi untuk item %. Stok saat ini: %, perubahan: %',
            NEW.item_id, v_current_stock, v_delta;
    END IF;

    -- Memperbarui stok secara otomatis
    UPDATE inventory_items
    SET stock_qty = stock_qty + v_delta
    WHERE item_id = NEW.item_id;

    RETURN NEW;
END;
$$;

-- =====================================================
-- 4. MEMASANG TRIGGER
-- =====================================================

DROP TRIGGER IF EXISTS trigger_update_stock
ON inventory_transactions;

CREATE TRIGGER trigger_update_stock
BEFORE INSERT ON inventory_transactions
FOR EACH ROW
EXECUTE FUNCTION trg_update_stock_and_journal();
