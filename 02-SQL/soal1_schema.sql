
-- SOAL 1.2: DESAIN SKEMA DATABASE GENERAL LEDGER
-- Database: PostgreSQL

-- 1. TABEL MASTER AKUN
CREATE TABLE chart_of_accounts (
    account_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_code VARCHAR(20) NOT NULL UNIQUE,
    account_name VARCHAR(150) NOT NULL,

    normal_balance CHAR(1) NOT NULL
        CHECK (normal_balance IN ('D', 'K')),

    report_classification VARCHAR(30) NOT NULL
        CHECK (
            report_classification IN (
                'ASET',
                'LIABILITAS',
                'EKUITAS',
                'PENDAPATAN',
                'BEBAN'
            )
        )
);

-- 2. TABEL HEADER JURNAL
CREATE TABLE journal_headers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trx_date DATE NOT NULL,
    ref_number VARCHAR(50) NOT NULL UNIQUE,
    description TEXT NOT NULL,

    status_posting VARCHAR(10) NOT NULL DEFAULT 'DRAFT'
        CHECK (status_posting IN ('DRAFT', 'POSTED'))
);

-- 3. TABEL RINCIAN JURNAL
CREATE TABLE journal_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    header_id BIGINT NOT NULL,
    account_id BIGINT NOT NULL,

    debit NUMERIC(18,2) NOT NULL DEFAULT 0,
    credit NUMERIC(18,2) NOT NULL DEFAULT 0,

    -- Relasi ke tabel header jurnal
    CONSTRAINT fk_lines_header
        FOREIGN KEY (header_id)
        REFERENCES journal_headers(id)
        ON DELETE RESTRICT,

    -- Relasi ke tabel master akun
    CONSTRAINT fk_lines_account
        FOREIGN KEY (account_id)
        REFERENCES chart_of_accounts(account_id)
        ON DELETE RESTRICT,

    -- Debit tidak boleh negatif
    CONSTRAINT chk_debit_nonnegative
        CHECK (debit >= 0),

    -- Kredit tidak boleh negatif
    CONSTRAINT chk_credit_nonnegative
        CHECK (credit >= 0),

    -- Debit dan kredit tidak boleh sama-sama nol
    CONSTRAINT chk_line_not_both_zero
        CHECK (NOT (debit = 0 AND credit = 0))
);

-- 4. INDEX UNTUK MEMBANTU PENCARIAN DATA
CREATE INDEX idx_journal_lines_header
    ON journal_lines(header_id);

CREATE INDEX idx_journal_lines_account
    ON journal_lines(account_id);
